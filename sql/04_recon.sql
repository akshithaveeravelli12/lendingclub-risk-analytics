-- =====================================================================
-- 04_recon.sql  |  End-to-end reconciliation SOURCE -> RAW -> STAGING -> MARTS
-- Writes PASS/FAIL per control to AUDIT.RECON_RESULTS (rerunnable per batch)
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE LOAN_WH;
USE DATABASE LOAN_RISK;

DELETE FROM AUDIT.RECON_RESULTS
WHERE BATCH_ID = (SELECT MAX(_BATCH_ID) FROM RAW.LC_LOANS_RAW);

INSERT INTO AUDIT.RECON_RESULTS
  (BATCH_ID, CHECK_NAME, LAYER_FROM, LAYER_TO, EXPECTED, ACTUAL, VARIANCE, TOLERANCE, STATUS)
SELECT
  BATCH_ID, CHECK_NAME, LAYER_FROM, LAYER_TO, EXPECTED, ACTUAL,
  ACTUAL - EXPECTED                                         AS VARIANCE,
  TOLERANCE,
  IFF(ABS(ACTUAL - EXPECTED) <= TOLERANCE, 'PASS', 'FAIL')  AS STATUS
FROM (
  WITH b AS (SELECT MAX(_BATCH_ID) AS id FROM RAW.LC_LOANS_RAW),
  raw_all AS (SELECT * FROM RAW.LC_LOANS_RAW WHERE _BATCH_ID = (SELECT id FROM b)),
  raw_ok  AS (SELECT * FROM raw_all WHERE TRY_TO_NUMBER(ID) IS NOT NULL),
  src     AS (SELECT METRIC_NAME, METRIC_VALUE FROM AUDIT.SOURCE_PROFILE WHERE BATCH_ID = (SELECT id FROM b)),
  checks AS (
    -- Source file -> RAW
    SELECT '01_ROW_COUNT' AS CHECK_NAME, 'SOURCE' AS LAYER_FROM, 'RAW' AS LAYER_TO,
           (SELECT METRIC_VALUE FROM src WHERE METRIC_NAME = 'ROW_COUNT') AS EXPECTED,
           (SELECT COUNT(*) FROM raw_all) AS ACTUAL, 0 AS TOLERANCE
    UNION ALL SELECT '02_SUM_LOAN_AMNT', 'SOURCE', 'RAW',
           (SELECT METRIC_VALUE FROM src WHERE METRIC_NAME = 'SUM_LOAN_AMNT'),
           (SELECT SUM(TRY_TO_NUMBER(LOAN_AMNT, 38, 2)) FROM raw_all), 1
    UNION ALL SELECT '03_SUM_TOTAL_PYMNT', 'SOURCE', 'RAW',
           (SELECT METRIC_VALUE FROM src WHERE METRIC_NAME = 'SUM_TOTAL_PYMNT'),
           (SELECT SUM(TRY_TO_NUMBER(TOTAL_PYMNT, 38, 2)) FROM raw_all), 1

    -- RAW (valid ids) -> STAGING
    UNION ALL SELECT '04_ROW_COUNT', 'RAW', 'STAGING',
           (SELECT COUNT(*) FROM raw_ok), (SELECT COUNT(*) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '05_JUNK_ROWS_EXCLUDED', 'RAW', 'STAGING',
           (SELECT METRIC_VALUE FROM src WHERE METRIC_NAME = 'NON_NUMERIC_ID_ROWS'),
           (SELECT COUNT(*) FROM raw_all) - (SELECT COUNT(*) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '06_SUM_LOAN_AMNT', 'RAW', 'STAGING',
           (SELECT SUM(TRY_TO_NUMBER(LOAN_AMNT, 38, 2)) FROM raw_ok), (SELECT SUM(LOAN_AMNT) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '07_SUM_FUNDED_AMNT', 'RAW', 'STAGING',
           (SELECT SUM(TRY_TO_NUMBER(FUNDED_AMNT, 38, 2)) FROM raw_ok), (SELECT SUM(FUNDED_AMNT) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '08_SUM_TOTAL_PYMNT', 'RAW', 'STAGING',
           (SELECT SUM(TRY_TO_NUMBER(TOTAL_PYMNT, 38, 2)) FROM raw_ok), (SELECT SUM(TOTAL_PYMNT) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '09_SUM_RECOVERIES', 'RAW', 'STAGING',
           (SELECT SUM(TRY_TO_NUMBER(RECOVERIES, 38, 2)) FROM raw_ok), (SELECT SUM(RECOVERIES) FROM STAGING.STG_LOANS), 0
    UNION ALL SELECT '10_UNMAPPED_STATUS', 'RAW', 'STAGING',
           0, (SELECT COUNT_IF(LOAN_STATUS_GROUP = 'UNKNOWN') FROM STAGING.STG_LOANS), 0

    -- STAGING -> MARTS
    UNION ALL SELECT '11_ROW_COUNT', 'STAGING', 'MARTS',
           (SELECT COUNT(*) FROM STAGING.STG_LOANS), (SELECT COUNT(*) FROM MARTS.FCT_LOAN), 0
    UNION ALL SELECT '12_SUM_LOAN_AMNT', 'STAGING', 'MARTS',
           (SELECT SUM(LOAN_AMNT) FROM STAGING.STG_LOANS), (SELECT SUM(LOAN_AMNT) FROM MARTS.FCT_LOAN), 0
    UNION ALL SELECT '13_SUM_NET_CHARGE_OFF', 'STAGING', 'MARTS',
           (SELECT SUM(NET_CHARGE_OFF_AMNT) FROM STAGING.STG_LOANS), (SELECT SUM(NET_CHARGE_OFF_AMNT) FROM MARTS.FCT_LOAN), 0
    UNION ALL SELECT '14_DUPLICATE_LOAN_ID', 'MARTS', 'MARTS',
           0, (SELECT COUNT(*) - COUNT(DISTINCT LOAN_ID) FROM MARTS.FCT_LOAN), 0
    UNION ALL SELECT '15_ORPHAN_BORROWER_KEY', 'MARTS', 'MARTS',
           0, (SELECT COUNT(*) FROM MARTS.FCT_LOAN f
               LEFT JOIN MARTS.DIM_BORROWER b ON b.BORROWER_KEY = f.BORROWER_KEY
               WHERE b.BORROWER_KEY IS NULL), 0
    UNION ALL SELECT '16_ORPHAN_ISSUE_DATE_KEY', 'MARTS', 'MARTS',
           0, (SELECT COUNT(*) FROM MARTS.FCT_LOAN f
               LEFT JOIN MARTS.DIM_DATE d ON d.DATE_KEY = f.ISSUE_DATE_KEY
               WHERE d.DATE_KEY IS NULL), 0
  )
  SELECT (SELECT id FROM b) AS BATCH_ID, * FROM checks
);

-- Results
SELECT CHECK_NAME, LAYER_FROM, LAYER_TO, EXPECTED, ACTUAL, VARIANCE, STATUS
FROM AUDIT.RECON_RESULTS
WHERE BATCH_ID = (SELECT MAX(_BATCH_ID) FROM RAW.LC_LOANS_RAW)
ORDER BY CHECK_NAME;
