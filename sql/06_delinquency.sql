-- =====================================================================
-- 06_delinquency.sql  |  Delinquency buckets on the active book (snapshot)
-- Active = not resolved (Current, Grace, Late 16-30, Late 31-120, Default).
-- The dataset is a single snapshot, so this replaces true month-to-month roll rates.
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE LOAN_WH;
USE DATABASE LOAN_RISK;

CREATE OR REPLACE VIEW MARTS.VW_DELINQUENCY_BUCKETS AS
SELECT
  VINTAGE_YEAR,
  GRADE,
  LOAN_STATUS_GROUP AS BUCKET,
  CASE LOAN_STATUS_GROUP
    WHEN 'CURRENT'      THEN 1
    WHEN 'GRACE_PERIOD' THEN 2
    WHEN 'LATE_16_30'   THEN 3
    WHEN 'LATE_31_120'  THEN 4
    WHEN 'DEFAULT'      THEN 5
  END AS BUCKET_ORDER,
  COUNT(*)       AS LOANS,
  SUM(OUT_PRNCP) AS OUTSTANDING_PRINCIPAL
FROM MARTS.FCT_LOAN
WHERE NOT IS_RESOLVED
GROUP BY VINTAGE_YEAR, GRADE, LOAN_STATUS_GROUP;

-- 4a. Share of outstanding balance in each bucket, by grade
WITH g AS (
  SELECT
    COALESCE(GRADE, 'ALL') AS GRADE,
    SUM(LOANS) AS ACTIVE_LOANS,
    SUM(OUTSTANDING_PRINCIPAL) AS BAL,
    SUM(IFF(BUCKET = 'CURRENT', OUTSTANDING_PRINCIPAL, 0))      AS BAL_CURRENT,
    SUM(IFF(BUCKET = 'GRACE_PERIOD', OUTSTANDING_PRINCIPAL, 0)) AS BAL_GRACE,
    SUM(IFF(BUCKET = 'LATE_16_30', OUTSTANDING_PRINCIPAL, 0))   AS BAL_16_30,
    SUM(IFF(BUCKET = 'LATE_31_120', OUTSTANDING_PRINCIPAL, 0))  AS BAL_31_120,
    SUM(IFF(BUCKET = 'DEFAULT', OUTSTANDING_PRINCIPAL, 0))      AS BAL_DEFAULT
  FROM MARTS.VW_DELINQUENCY_BUCKETS
  GROUP BY ROLLUP (GRADE)
)
SELECT
  GRADE,
  ACTIVE_LOANS,
  ROUND(BAL / 1e6, 1)                       AS OUTSTANDING_MILLIONS,
  ROUND(100 * BAL_CURRENT / BAL, 2)         AS PCT_CURRENT,
  ROUND(100 * BAL_GRACE / BAL, 2)           AS PCT_GRACE,
  ROUND(100 * BAL_16_30 / BAL, 2)           AS PCT_LATE_16_30,
  ROUND(100 * BAL_31_120 / BAL, 2)          AS PCT_LATE_31_120,
  ROUND(100 * BAL_DEFAULT / BAL, 2)         AS PCT_DEFAULT,
  ROUND(100 * (BAL - BAL_CURRENT) / BAL, 2) AS PCT_DELINQUENT_BAL,
  ROUND(100 * (BAL_31_120 + BAL_DEFAULT)
        / NULLIF(BAL - BAL_CURRENT, 0), 2)  AS PCT_SEVERE_OF_DELINQ
FROM g
ORDER BY GRADE;

-- 4b. By vintage year
WITH v AS (
  SELECT
    COALESCE(VINTAGE_YEAR::VARCHAR, 'ALL') AS VINTAGE_YEAR,
    SUM(LOANS) AS ACTIVE_LOANS,
    SUM(OUTSTANDING_PRINCIPAL) AS BAL,
    SUM(IFF(BUCKET = 'CURRENT', OUTSTANDING_PRINCIPAL, 0)) AS BAL_CURRENT,
    SUM(IFF(BUCKET IN ('LATE_31_120', 'DEFAULT'), OUTSTANDING_PRINCIPAL, 0)) AS BAL_30PLUS
  FROM MARTS.VW_DELINQUENCY_BUCKETS
  GROUP BY ROLLUP (VINTAGE_YEAR)
)
SELECT
  VINTAGE_YEAR,
  ACTIVE_LOANS,
  ROUND(BAL / 1e6, 1)                       AS OUTSTANDING_MILLIONS,
  ROUND(100 * (BAL - BAL_CURRENT) / BAL, 2) AS PCT_DELINQUENT_BAL,
  ROUND(100 * BAL_30PLUS / BAL, 2)          AS PCT_30PLUS_DPD_BAL
FROM v
ORDER BY VINTAGE_YEAR;
